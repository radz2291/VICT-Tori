import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { memoryIntent } from '../packages/memory/intent.mjs';
import { prefixes, verbs, boundaries } from './memory-intent-fixtures.mjs';

const variants=text=>[...new Set([text,text.replaceAll('’',"'")])];
const cases=[
  ...prefixes.flatMap(([text,expected],i)=>variants(text).map(value=>['Prefix '+(i+1),value,expected])),
  ...verbs.flatMap(([yes,no],i)=>[
    ...variants(yes).map(text=>['Verb '+(i+1)+' affirmative',text,{kind:'explicit',contextual:false}]),
    ...variants(no).map(text=>['Verb '+(i+1)+' negation twin',text,{kind:'ineligible',reason:'negated-request'}]),
  ]),
  ...boundaries.flatMap(([text,expected,origin],i)=>variants(text).map(value=>['Boundary '+(i+1),value,expected,origin])),
];

test('pinned vocabulary, verb negation twins and trusted origins',async t=>{
  assert.equal(prefixes.length,24);
  assert.equal(verbs.length,23);
  const observed=[];
  for(const [group,text,expected,origin='operator'] of cases){
    const actual=memoryIntent(text,origin);
    observed.push([group,JSON.stringify(text),origin,actual.kind,actual.reason??(actual.kind==='explicit'?(actual.contextual?'contextual':'non-contextual'):'—')]);
    await t.test(group+' · '+origin+' · '+JSON.stringify(text),()=>assert.deepEqual(actual,expected));
  }
  if(process.env.TORI_MEMORY_INTENT_EVIDENCE){
    const escape=value=>value.replaceAll('|','\\|');
    writeFileSync(process.env.TORI_MEMORY_INTENT_EVIDENCE,[
      '# Observed memory intent vocabulary','',
      'Generated by tests/memory-intent.test.mjs from the pinned owner matrix and additional boundary cases. “Explicit” opens only the proposal path; confirmation owns every save. Contracted verbs were exercised with both straight and curly apostrophes.','',
      '| Case | Current text | Origin | Observed classification | Reason or context |',
      '| --- | --- | --- | --- | --- |',
      ...observed.map(row=>'| '+row.map(escape).join(' | ')+' |'),'',
    ].join('\n'));
  }
});
