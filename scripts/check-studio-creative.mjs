import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';

const [entry, chrome, url] = process.argv.slice(2);
const { chromium } = await import(pathToFileURL(entry));
const browser = await chromium.launch({ executablePath: chrome });
try {
  const page = await browser.newPage({ viewport: { width: 1531, height: 668 } });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const choice = async (name, option) => {
    await page.getByLabel(name, { exact: true }).click();
    await page.getByRole('option', { name: option, exact: true }).click();
  };
  await page.goto(url);
  await button('Creative').click();
  await button('Compare directions').click();
  assert.deepEqual(await page.getByRole('region', { name: 'Direction comparison' }).getByRole('heading').allTextContents(), ['Metallic', 'Biological', 'Architectural']);
  assert.equal(await page.locator('.authoring-page:visible .svelte-flow__edge').count(), 6);
  await button('Select Metallic').click();
  await page.locator('.authoring-page:visible .svelte-flow__node.selected[aria-label="Metallic"]').waitFor();
  console.log('Native selection and six edges passed.');
  await button('Inspector').click();
  await page.getByLabel('Direction notes in Inspector').fill('Synthetic titanium');
  await page.getByLabel('Direction notes in Inspector').press('Tab');
  assert.equal(await page.getByLabel('Metallic notes').inputValue(), 'Synthetic titanium');
  await choice('Explicit context source', 'Source idea');
  await page.getByText('Context preview:', { exact: false }).waitFor();
  await button('Preferred direction').click();
  await button('Branch selected direction').click();
  await page.getByRole('heading', {name: 'Metallic variation'}).waitFor();
  await button('Undo').click();
  await page.getByRole('heading', {name: 'Metallic variation'}).waitFor({state:'detached'});
  await button('Redo').click();
  await page.getByRole('heading', {name: 'Metallic variation'}).waitFor();
  await button('Link references').click();
  await choice('Reference target', 'Biological');
  await button('Connect reference').click();
  await page.getByRole('dialog').getByRole('alert').waitFor();
  await button('Cancel').click();
  await button('Link references').click();
  await choice('Reference target', 'Architectural');
  await button('Connect reference').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await button('Save draft').click();
  console.log('Branch, reference rejection/acceptance, shared Inspector, and save passed.');
  await button('Simulate selected direction').click();
  await choice('Creative simulation intent', 'Run To');
  assert.equal(await button('Create simulated run').isDisabled(), true);
  await choice('Creative simulation intent', 'Run From');
  assert.equal(await button('Create simulated run').isDisabled(), true);
  await choice('Creative simulation intent', 'Run Node');
  await button('Create simulated run').click();
  await page.getByRole('heading', { name: 'Execution trace', exact: true }).waitFor();
  await button('Open definition').click();
  await button('Simulate selected direction').click();
  await page.getByText('Current inputs', { exact: false }).waitFor();
  await page.getByRole('img', { name: 'Synthetic artifact variation 1' }).waitFor();
  const firstArtifact = await page.getByText('Current inputs', { exact: false }).innerText();
  await choice('Creative simulation intent', 'Reuse current artifact');
  await button('Create simulated run').click();
  await page.getByRole('heading', { name: 'Reuse current artifact · succeeded' }).waitFor();
  await button('Open definition').click();
  await page.getByLabel('Direction notes in Inspector').fill('Synthetic brass');
  await page.getByLabel('Direction notes in Inspector').press('Tab');
  await button('Simulate selected direction').click();
  await page.getByText('Stale inputs', { exact: false }).waitFor();
  await choice('Creative simulation intent', 'Generate another variation');
  await button('Create simulated run').click();
  await page.getByRole('heading', { name: 'Generate another variation · succeeded' }).waitFor();
  await page.reload();
  await button('Creative').click();
  await button('Simulate selected direction').click();
  await page.getByText('Stale inputs', { exact: false }).waitFor();
  assert.equal(await button('Inspect artifact run').count(), 2);
  assert.ok((await page.getByText('Stale inputs', { exact: false }).allTextContents())
    .some(text => text.split(' · ')[0] === firstArtifact.split(' · ')[0]));
  await page.getByRole('img', { name: 'Synthetic artifact variation 2' }).waitFor();
  await button('Close').click();
  await button('Create workflow from selection').click();
  const workflow = page.getByRole('region', { name: 'Workflow graph' });
  const request = workflow.locator('[data-graph-node]').filter({ hasText: 'Metallic source' });
  assert.equal(await request.getByRole('textbox', { name: 'Request brief', exact: true }).inputValue(), 'Synthetic brass');
  await workflow.locator('.svelte-flow__edge').waitFor();
  if (!(await page.getByText('Creative source metallic', { exact: false }).isVisible())) {
    await button('Inspector').click();
  }
  await page.getByText('Creative source metallic', { exact: false }).waitFor();
  await page.getByText('"id":"creative-idea"', { exact: false }).waitFor();
  await button('Save draft').click();
  await page.reload();
  await button('Workflows').click();
  assert.equal(await request.getByRole('textbox', { name: 'Request brief', exact: true }).inputValue(), 'Synthetic brass');
  assert.deepEqual(errors, []);
  console.log('PASS Creative adapter unsupported cases, version reuse, staleness, variations, conversion, and reload.');
} finally { await browser.close(); }
